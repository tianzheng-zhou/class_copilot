test('upload, confirm analysis, refresh, and synchronize another tab', async ({ page, context }) => {
  await createClass(page, '导入与同步')
  const second = await context.newPage()
  await second.goto(page.url())
  await page.getByRole('button', { name: '音频来源', exact: true }).click()
  const samples = 8000
  const wav = Buffer.alloc(44 + samples * 2)
  wav.write('RIFF', 0)
  wav.writeUInt32LE(36 + samples * 2, 4)
  wav.write('WAVE', 8)
  wav.write('fmt ', 12)
  wav.writeUInt32LE(16, 16)
  wav.writeUInt16LE(1, 20)
  wav.writeUInt16LE(1, 22)
  wav.writeUInt32LE(16000, 24)
  wav.writeUInt32LE(32000, 28)
  wav.writeUInt16LE(2, 32)
  wav.writeUInt16LE(16, 34)
  wav.write('data', 36)
  wav.writeUInt32LE(samples * 2, 40)
  for (let i = 0; i < samples; i++) wav.writeInt16LE(2000, 44 + i * 2)
  await page
    .locator('input[type=file]')
    .setInputFiles({ name: 'browser-audio.wav', mimeType: 'audio/wav', buffer: wav })
  const dialog = page.getByRole('dialog', { name: '分析这份录音' })
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: '开始分析', exact: true }).click()
  await page.getByRole('button', { name: '关闭面板' }).click()
  await expect(second.locator('.transcript-row')).toHaveCount(1, { timeout: 15000 })
  await second.reload()
  await expect(second.locator('.transcript-row')).toHaveCount(1)
  await second.getByRole('textbox', { name: '聊天消息' }).fill('从另一标签页发送')
  await second.getByRole('textbox', { name: '聊天消息' }).press('Enter')
  await expect(page.locator('.user-message')).toContainText('从另一标签页发送')
  await expect(page.locator('.assistant-message .markdown')).toContainText('矩阵表示线性映射')
  await second.close()
})
